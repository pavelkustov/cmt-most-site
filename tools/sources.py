"""Где лежат локальные исходники сайта: книга сотрудников, анкета новостей, фотографии.

Все три живут внутри репозитория, в папке `data`, и в git не уходят (правила
в `.gitignore`), потому что там персональные данные и десятки мегабайт снимков.
У каждой папки свой README с пояснением, откуда берется файл и кто его читает.

До 22.09.2026 они лежали на рабочем столе рядом с папкой репозитория. Если файла
в `data` нет, а на старом месте он есть, скрипты берут старое место и печатают
напоминание перенести, чтобы ничего не ломалось на полпути.

Запуск: не запускается, это общий модуль для скриптов из `tools`.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent


def pick(new, old, what):
    """Путь к исходнику: сперва место в репозитории, потом старое рядом с репо."""
    if new.exists() or not old.exists():
        return new
    print("исходник " + what + " лежит на старом месте: " + str(old))
    print("перенесите его в " + str(new.parent) + ", скрипты ждут его там")
    return old


BOOK = pick(ROOT / "data" / "book" / "ЦМТ Мост.xlsx",
            ROOT.parent / "ЦМТ Мост.xlsx", "«ЦМТ Мост.xlsx»")
FORM = pick(ROOT / "data" / "news" / "011_Новости.docx",
            ROOT.parent / "011_Новости.docx", "«011_Новости.docx»")
PHOTOS = pick(ROOT / "data" / "photos", ROOT.parent / "Фото", "папка с фотографиями новостей")
